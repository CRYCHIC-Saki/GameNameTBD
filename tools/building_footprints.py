def market_contour(part):
    art = part["sprite"]
    if art in ("greens", "barrel") or part["id"] == "door-prop-2":  # mill beside Chen's shop
        return MARKET_FIXTURES.get(art)
    if part["id"].startswith(("market-", "waterfront-")):
        return MARKET_COUNTERS.get(art) or MARKET_FIXTURES.get(art)
    return None


def building_mask(size, contour, flip=False):
    """Rasterize closed masonry, including unpainted door and window interiors."""
    width, height = size
    points = [(round((100-x if flip else x)*(width-1)/100),round(y*(height-1)/100))
              for x,y in contour]
    image = Image.new("L",size)
    ImageDraw.Draw(image).polygon(points,fill=255)
    return image


def stamp_building(mask, contour, anchor, size, flip=False):
    w, h = (max(1,round(v)) for v in size)
    x,y = anchor
    left,top = round(x-w/2),round(y-h)
    mask.paste(1,(left,top,left+w,top+h),building_mask((w,h),contour,flip))


def wall_clearance(mask, world_scale):
    """Add half a shoulder (after the existing foot radius) at the sides only."""
    radius = round(16/world_scale)
    occupied = np.asarray(mask,dtype=bool)
    wide = occupied.copy()
    for offset in range(1,radius+1):
        wide[:,offset:] |= occupied[:,:-offset]
        wide[:,:-offset] |= occupied[:,offset:]
    return wide
